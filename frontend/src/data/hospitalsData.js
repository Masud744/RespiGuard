/**
 * Calculates straight-line distance in kilometers using Haversine formula.
 */
export function calculateDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371; // Earth radius in km
  const dLat = (lat2 - lat1) * (Math.PI / 180);
  const dLon = (lon2 - lon1) * (Math.PI / 180);
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos(lat1 * (Math.PI / 180)) *
    Math.cos(lat2 * (Math.PI / 180)) *
    Math.sin(dLon / 2) *
    Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  const d = R * c;
  return Math.round(d * 10) / 10;
}

/**
 * Returns hospitals sorted by distance relative to the given lat/lon coordinates.
 */
export function getNearbyHospitalsSorted(userLat, userLon) {
  return HOSPITALS.map((h) => ({
    ...h,
    distanceKm: calculateDistanceKm(userLat, userLon, h.lat, h.lon)
  })).sort((a, b) => a.distanceKm - b.distanceKm);
}
